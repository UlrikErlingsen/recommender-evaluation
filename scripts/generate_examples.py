"""Regenerate RecommendSignal's deterministic fictional examples."""

from __future__ import annotations

from pathlib import Path
import sys

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from recommendsignal.examples import (  # noqa: E402
    make_catalog_template,
    make_demo_catalog,
    make_demo_events,
    make_event_template,
)


def main() -> None:
    examples = ROOT / "examples"
    examples.mkdir(exist_ok=True)
    events = make_demo_events()
    catalog = make_demo_catalog()
    event_template = make_event_template()
    catalog_template = make_catalog_template()

    events.to_csv(examples / "recommendsignal-fictional-events.csv", index=False)
    catalog.to_csv(examples / "recommendsignal-fictional-items.csv", index=False)
    event_template.to_csv(examples / "recommendsignal-event-template.csv", index=False)
    catalog_template.to_csv(examples / "recommendsignal-item-template.csv", index=False)

    with pd.ExcelWriter(examples / "recommendsignal-fictional-data.xlsx", engine="openpyxl") as writer:
        events.to_excel(writer, sheet_name="interactions", index=False)
        catalog.to_excel(writer, sheet_name="items", index=False)
        pd.DataFrame(
            [
                {"field": "status", "value": "Entirely fictional data generated by code."},
                {"field": "purpose", "value": "Demonstrate temporal offline recommendation evaluation."},
            ]
        ).to_excel(writer, sheet_name="read_me", index=False)

    with pd.ExcelWriter(examples / "recommendsignal-starter-templates.xlsx", engine="openpyxl") as writer:
        event_template.to_excel(writer, sheet_name="interactions", index=False)
        catalog_template.to_excel(writer, sheet_name="items", index=False)


if __name__ == "__main__":
    main()
